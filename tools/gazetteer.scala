// A GAZETTEER'S DATA (specs/design.md §17 "Round 4"): a TSV of official names — name, kind (city | district), city
// (a district's city's name), uk, ru, en (exonyms, optional), common (yes: a common word — named only when written as
// a place), more (other forms, `;` between) — to the JSON `Places.parse` reads, every place's forms generated by
// `PlaceForms` (Polish cases, Ukrainian and Russian transliteration and cases, folded). Lines starting with # are
// comments (the source's citation is kept in the JSON's `source`).
//   scala-cli run tools/gazetteer.scala -- <places.tsv> <places.json>

import okay.effects.json.Json
import okay.facts.router.{PlaceForms, Spell}

@main def gazetteer(in: String, out: String): Unit =
  val lines = java.nio.file.Files.readAllLines(java.nio.file.Path.of(in)).toArray.toVector.map(_.toString)
  val source = lines.filter(_.startsWith("#")).map(_.drop(1).trim).mkString(" ")
  val rows = lines.filterNot(l => l.startsWith("#") || l.trim.isEmpty).map(_.split("\t", -1).toVector)
  def slug(s: String) = okay.facts.Words.split(s).mkString("-")
  def col(r: Vector[String], i: Int) = r.lift(i).map(_.trim).filter(_.nonEmpty)
  val places = rows.map { r =>
    val (name, kind, city) = (r(0).trim, r(1).trim, col(r, 2).getOrElse(""))
    val (uk, ru, en) = (col(r, 3), col(r, 4), col(r, 5))
    val more = col(r, 7).toVector.flatMap(_.split(";").map(_.trim).filter(_.nonEmpty))
    val id = if kind == "district" then s"${slug(city)}/${slug(name)}" else slug(name)
    Json.obj("id" -> Json.str(id), "name" -> Json.obj("pl" -> Json.str(name),
        "uk" -> Json.str(uk.getOrElse(PlaceForms.cyrillic(name, okay.facts.Lang.uk))),
        "ru" -> Json.str(ru.getOrElse(PlaceForms.cyrillic(name, okay.facts.Lang.ru))),
        "en" -> Json.str(en.getOrElse(name))),
      "kind" -> Json.str(kind), "city" -> Json.str(if kind == "district" then slug(city) else ""),
      "forms" -> Json.Arr(PlaceForms.forms(name, uk, ru, en, more).map(Json.str)),
      "common" -> Json.bool(col(r, 6).contains("yes")))
  }
  val ids = places.map(_("id").string)
  require(ids.distinct.size == ids.size, s"an id twice: ${ids.diff(ids.distinct).take(5)}")
  val doc = Json.obj("about" -> Json.str("A GAZETTEER of Polish places (okay-facts specs/design.md §17 \"Round 4\"): " +
      "generated by okay-facts' tools/gazetteer.scala from places.tsv — never edited by hand"),
    "source" -> Json.str(source), "places" -> Json.Arr(places))
  java.nio.file.Files.writeString(java.nio.file.Path.of(out), Json.print(doc) + "\n")
  println(s"${places.size} places, ${places.map(_("forms").list.size).sum} forms -> $out")
